#!/usr/bin/env python3
"""mksndp.py - the game's own sound code ($9527-$96BE: the four blocking effects, the
per-frame player at $9579 and the beeper routines) as a module that runs from Elite's
sound bank at $C000 (segment 3), from the converted original source (elite_ref.asm).

The code is the original, with three changes:
  * OUT ($FE),A (the Spectrum beeper, bit 4) -> CALL spk_a: the Z88 speaker (Blink COM
    SBIT), the rest of COM as OZ has it (SPKC, set by the glue);
  * LD A,($FC0E) (sound on/off, in game bank 3, which is not in segment 3 while this
    runs) -> LD A,(SND_ON) (copied there by the glue);
  * references to its own addresses (a jump table, the self-modified operands) become
    label expressions, so the module may grow and run elsewhere.
Plus spk_a and a one-bit BEEPER (the ROM routine at $03B5) for the two ROM calls.
Usage: mksndp.py elite_ref.asm sndp.asm"""
import re, sys

FIRST, END = 0x9527, 0x96BF          # [FIRST, END): the sound code
src = open(sys.argv[1]).read().splitlines()

lines = []                           # (address, text) for the range
for l in src:
    m = re.match(r'^\.L_([0-9A-F]{4})\s+(.*)$', l)
    if not m:
        continue
    a = int(m.group(1), 16)
    if FIRST <= a < END:
        lines.append((a, m.group(2).strip()))
starts = [a for a, _ in lines]

def label_expr(v):
    """an address inside the range as a label expression"""
    base = max(s for s in starts if s <= v)
    return 'L_%04X' % base if base == v else 'L_%04X+%d' % (base, v - base)

out = ['; sndp.asm - generated by tools/mksndp.py from elite_ref.asm ($9527-$96BE): the',
       '; game\'s sound code, run from Elite\'s sound bank in segment 3 (see the header there)',
       '        module  sndp',
       '        include "elite.inc"',
       '        xdef    L_9527, L_9532, L_953D, L_9548, L_9579, beeper',
       '        org     $C000', '']
for a, ins in lines:
    if ins == 'OUT ($FE),A':
        ins = 'CALL spk_a'
    elif ins == 'LD A,($FC0E)':
        ins = 'LD A,(SND_ON)'
    def fix(m):
        v = int(m.group(1), 16)
        return label_expr(v) if FIRST <= v < END else m.group(0)
    ins = re.sub(r'\$([0-9A-F]{4})\b', fix, ins)
    for t in re.findall(r'\bL_([0-9A-F]{4})\b', ins):
        if not FIRST <= int(t, 16) < END:
            sys.exit('reference outside the sound code: %s at %04X' % (ins, a))
    out.append('.L_%04X  %s' % (a, ins))

out += ['',
'; spk_a: the Spectrum beeper bit (bit 4 of A) to the Z88 speaker: Blink COM with SBIT',
'; (bit 6) set or clear, the other bits as OZ has them (SPKC).  A and flags change.',
'spk_a:  and     $10',
'        ld      a,(SPKC)',
'        jr      z,spk_w',
'        or      $40',
'spk_w:  out     ($B0),a',
'        ret',
'',
'; beeper: the ROM BEEPER ($03B5) for the Z88: DE = cycles, HL = the ROM\'s pitch value',
'; (a half cycle of 4 * (HL + 30) T at 3.5 MHz).  The delay loop takes 26 T a turn:',
'; turns = HL >> 3 + HL >> 6 + 2 keeps the ROM\'s pitch on the Z88\'s 3.2768 MHz.',
'beeper: di',
'        push    de',
'        srl     h',
'        rr      l',
'        srl     h',
'        rr      l',
'        srl     h',
'        rr      l              ; HL >> 3',
'        ld      d,h',
'        ld      e,l',
'        srl     d',
'        rr      e',
'        srl     d',
'        rr      e',
'        srl     d',
'        rr      e              ; DE = HL >> 6 (of the original)',
'        add     hl,de',
'        inc     hl',
'        inc     hl             ; + 2: with the 70 T around the loop, a half cycle of',
'        pop     de             ; 0.936 * 4 * (HL + 30) T, the ROM\'s time at 3.2768 MHz',
'        ld      a,(SPKC)',
'        ld      c,a',
'bp_cyc: ld      a,c',
'        or      $40',
'        out     ($B0),a',
'        push    hl',
'        call    bp_dly',
'        pop     hl',
'        ld      a,c',
'        out     ($B0),a',
'        push    hl',
'        call    bp_dly',
'        pop     hl',
'        dec     de',
'        ld      a,d',
'        or      e',
'        jr      nz,bp_cyc',
'        ei',
'        ret',
'bp_dly: dec     hl',
'        ld      a,h',
'        or      l',
'        jr      nz,bp_dly',
'        ret']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('%s: %d lines of the original, %d bytes of it' % (sys.argv[2], len(lines), END - FIRST))
