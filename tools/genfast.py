# 1. div_hl_a_de ($AFA8): BC = (HL:A) * $100 / DE, HL = remainder, A = 0
e("; BC = (HL:A) * 256 / DE (replaces $AFA8).  Quotient bits are collected inverted (carry")
e("; = 'did not fit') in A, high byte first, then complemented.")
e("fdiv_hl_a_de:")
for i in range(8):
    e("        adc     a,a")
    e("        adc     hl,hl")
    e("        jp      c,dha_o%d" % i)
    e("        sbc     hl,de")
    e("        jr      nc,dha_k%d" % i)
    e("        add     hl,de")
    e("dha_k%d:" % i)
    stubs.append("dha_o%d: or a\n        sbc     hl,de\n        or      a\n        jp      dha_k%d" % (i, i))
e("        adc     a,a")
e("        cpl")
e("        ld      b,a")
for i in range(8, 16):
    e("        add     hl,hl")
    e("        jp      c,dha_o%d" % i)
    e("        sbc     hl,de")
    e("        jr      nc,dha_k%d" % i)
    e("        add     hl,de")
    e("dha_k%d:" % i)
    e("        rla")
    stubs.append("dha_o%d: or a\n        sbc     hl,de\n        or      a\n        jp      dha_k%d" % (i, i))
e("        cpl")
e("        ld      c,a")
e("        ld      a,b             ; flags as the original's last RL B (C clear)")
e("        or      a")
e("        ld      a,0")
e("        ret")
e("")
# 2. AC8B: 8-bit restoring division, A:E / B, quotient into C ($FE marker)
e("; C = (A:E) / B, 8 bits (replaces the loop at $AC8B, C = $FE on entry)")
e("fdiv_ac8b:")
for i in range(8):
    e("        sla     e")
    e("        rla")
    e("        jp      c,d8_o%d" % i)
    e("        cp      b")
    e("        jr      c,d8_n%d" % i)
    e("        sub     b")
    e("d8_n%d:  ccf" % i)
    e("        rl      c")
    stubs.append("d8_o%d:  sub b\n        or      a\n        jp      d8_n%d" % (i, i))
e("        ret")
e("")
# 3. div_coord_by_b ($7CD5) and the $7CFB entry
e("; starfield division (replaces $7CD5): C = (A:L << 3) / B in 6 bits, then into $7CFB")
e("fdiv_coord:")
for k in range(3):
    e("        sla     l")
    e("        rla")
e("        ld      c,$F8")
e("        cp      b")
e("        jr      c,dc_n0")
e("        sub     b")
e("dc_n0:   ccf")
e("        rl      c")
for i in range(1, 6):
    e("        sla     l")
    e("        rla")
    e("        jp      c,dc_o%d" % i)
    e("        cp      b")
    e("        jr      c,dc_n%d" % i)
    e("        sub     b")
    e("dc_n%d:   ccf" % i)
    e("        rl      c")
    stubs.append("dc_o%d:  sub b\n        or      a\n        jp      dc_n%d" % (i, i))
e("        and     a")
e("        ret     z")
e("; D = A * 256 / B, 8 bits (replaces $7CFB)")
e("fdiv_7cfb:")
e("        ld      d,$FE")
for i in range(8):
    e("        add     a,a")
    e("        jp      c,dd_o%d" % i)
    e("        cp      b")
    e("        jr      c,dd_n%d" % i)
    e("        sub     b")
    e("dd_n%d:   ccf" % i)
    e("        rl      d")
    stubs.append("dd_o%d:  sub b\n        or      a\n        jp      dd_n%d" % (i, i))
e("        ret")
e("")
e("; overflow cases (the shifted-out bit means the divisor fits)")
for s in stubs:
    e(s)
e("fast_end:")
# 4. token lookup ($D45F): start of every 4th "other token", from the reference image
import os
img = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'elite_ref.bin'), 'rb').read()
mem = lambda a: img[a - 0x4000]
base = mem(0xF11C) | mem(0xF11D) << 8
starts = [base]
while len(starts) < 214:
    a = starts[-1]
    while mem(a): a += 1
    starts.append(a + 1)
assert starts[-1] < 0xFF00, hex(starts[-1])
